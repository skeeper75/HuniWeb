# -*- coding: utf-8 -*-
"""흐름상 반드시 있는데 원장 735행에 대응 행이 없는 단계를 processes_def 에 심는다.
이 단계들이 그대로 gaps.csv 의 「가 원장에 행 없음」이 된다. (1회용 패치)"""
import re

EX = {
    'P01': [("카테고리 트리 ↔ webadmin 상품군의 매핑 규약", "huni-mall", "김동학+서희항",
             "몰 카테고리와 webadmin 상품군을 무엇으로 잇는지 규약이 원장에 없다")],
    'P02': [("검색 결과 0건 안내 화면", "huni-mall", "김동학",
             "결과 없음일 때 무엇을 보여 주는지 원장에 행이 없다")],
    'P03': [("상세 → 주문옵션 위젯으로 넘어가는 진입 지점(CTA)", "huni-mall", "김동학",
             "상세를 읽은 손님이 위젯으로 들어가는 자리가 원장에 행으로 없다")],
    'P12': [("에디터 산출물 변환 실패 처리", "huni-mall", "서희항",
             "인쇄용 파일 변환이 실패했을 때의 손님 안내·재시도가 원장에 없다")],
    'P16': [("주문등록 S2S 실패 재전송·수기 보정", "webadmin", "김동학+서희항",
             "S2S 가 실패하면 주문이 후니로 안 넘어가는데 복구 경로가 원장에 없다")],
    'P19': [("무통장 입금 확인 → 결제완료 전이", "shopby", "최숙진",
             "입금대기에서 결제완료로 넘어가는 확인 단계가 원장에 행으로 없다")],
    'P24': [("배송지 변경 가능 시점 정책(출고 전까지)", "shopby", "최숙진",
             "언제까지 배송지를 바꿀 수 있는지 정책이 원장에 없다")],
}

p = 'processes_def.py'
s = open(p).read()
for pid, items in EX.items():
    pat = re.compile(r"(\{\s*'id': '%s',[\s\S]*?)'extra': \[\]," % pid)
    s, n = pat.subn(lambda m: m.group(1) + "'extra': " + repr(items) + ",", s, count=1)
    assert n == 1, pid
open(p, 'w').write(s)
print('패치 완료')
